// Refreshes handoff/Page-replication-code.md and app/screens.js from the live source.
//   node handoff/build-replication-code.cjs
// Every code block in the Markdown is replaced with the current file it names, sections listed in
// ADD are appended when missing, and app/screens.js becomes a read-only concatenation of the renderers.
// Run it after changing any file under app/ so the handoff never drifts from the build.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),app=path.join(root,'app'),doc=path.join(__dirname,'Page-replication-code.md');
const read=f=>fs.readFileSync(path.join(app,f),'utf8').replace(/\s+$/,'');
const lang=f=>f.endsWith('.html')?'html':'javascript';
const shot=n=>`[${n}](../design/screens/${n}.png)`;

// Sections for files added after the original kit. Inserted before "Routing, actions…".
const ADD=[
 {title:'Debrief recap',file:'pages/debrief-recap.js',refs:['P16b-recap-trace','P16c-recap-test'],
  actions:'recapNext, recapBack, recapDone, toggleRecap',
  text:'Two full-screen slides over the store loop before the detailed debrief. Headings, explanations and figures are live HTML; each slide is narrated when recorded. Media never gates the flow. See production/Debrief-media.md.'},
 {title:'Voices, feedback audio and sound',file:'audio.js',refs:[],
  actions:'introVoice, briefVoice, recapVoice, closingVoice, say (feedback), answer cues',
  text:'Plays recorded lines with caption and device-voice fallback, splits feedback into recorded segments, and adds shop ambience, opening effects, answer cues and the recap music bed. See production/Audio.md.'},
 {title:'Agent-led flow (prototype)',file:'agent.js',refs:[],
  actions:'begin, next, join, flag, approach, fix, slot, acct, run, nextRule, handoff, restart',
  text:'The primary build, opened from app/index.html: the whole simulation as an agent-led chat. Same content, engine, scoring, log and save key as app.js. See handoff/CLAUDE.md.'},
 {title:'Audio manifest',file:'audio-manifest.js',refs:[],actions:'none (data)',
  text:'Generated by production/build-voice-lines.cjs from production/voice-lines.json. A null entry means that line is not recorded yet.'}
];
// Prose updates for sections whose behaviour changed after the original kit.
const PROSE={
 'pages/opening.js':'Emit the shell with the MIVA Open University logo, collect a name, play the five caption cues with their recorded lines and shop sound, and enter audit. Cue, pause and audio timing are in app.js and audio.js.',
 'pages/debrief.js':'Calculate the weighted score from committed evidence. Opens after the two-slide recap (pages/debrief-recap.js). Expand personal feedback and reflect; reflection has zero score weight.',
 'app.js':'This controller owns the active page, grading events, idempotent corrections and repairs, transient inspector selections, dialogue timers, audio hand-offs (audio.js) and local saving.'
};

let md=fs.readFileSync(doc,'utf8');
const anchor='## Routing, actions, persistence and review modal';
for(const a of ADD){
 if(md.includes('**Source**: `app/'+a.file+'`'))continue;
 md=md.replace(anchor,`## ${a.title}\n**Source**: \`app/${a.file}\`  \n**Actions**: ${a.actions}\n${a.text}\n\n\`\`\`${lang(a.file)}\n\`\`\`\n\n${anchor}`);
 const row=`| ${a.title} | [${a.file}](../app/${a.file}) | ${a.refs.map(shot).join(' · ')||'—'} |`;
 md=md.replace(/(\| Routing, actions, persistence and review modal \|)/,row+'\n$1');
}
// Refresh prose and code for every "**Source**: `app/…`" section.
md=md.replace(/(## [^\n]+\n\*\*Source\*\*: `app\/([^`]+)`  \n\*\*Actions\*\*: [^\n]*\n)([^\n]*)(\n+)```(\w+)\n[\s\S]*?\n?```/g,
 (m,head,file,prose,gap,l)=>{if(!fs.existsSync(path.join(app,file)))throw Error('missing source '+file);
  return head+(PROSE[file]||prose)+gap+'```'+lang(file)+'\n'+read(file)+'\n```'});
fs.writeFileSync(doc,md);

const order=[...read('review.html').matchAll(/src="([^"]+\.js)"/g)].map(m=>m[1]).filter(f=>f.startsWith('pages/')||f==='shared.js');
fs.writeFileSync(path.join(app,'screens.js'),'// GENERATED reference copy by handoff/build-replication-code.cjs. review.html does not load it as a single file.\n// Edit app/shared.js and app/pages/*.js instead, then re-run the script.\n'+order.map(f=>`\n// ---- ${f} ----\n`+read(f)).join('\n')+'\n');
console.log(`Page-replication-code.md: ${(md.match(/\*\*Source\*\*/g)||[]).length} sections refreshed. screens.js: ${order.length} files.`);
